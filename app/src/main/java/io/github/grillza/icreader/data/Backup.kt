package io.github.grillza.icreader.data

import kotlinx.serialization.Serializable

/** The cards part of a backup file (a zip with this as backup.json, plus the card photos). */
@Serializable
data class BackupFile(
    val format: String = FORMAT,
    val version: Int = 1,
    val createdAt: Long = 0,
    val cards: List<SavedCard> = emptyList(),
) {
    companion object {
        const val FORMAT = "ic-reader-backup"
        const val CARDS_ENTRY = "backup.json"
        const val IMAGES_DIR = "images/"
    }
}

/** What a restore did. */
data class RestoreResult(val added: Int, val updated: Int)

/**
 * Restoring merges a backup into the saved cards instead of replacing them, so nothing scanned
 * since the backup is lost: new cards are added, and a card already here gets the backup's
 * history merged into its own. Pure (unit tested).
 */
object BackupMerge {

    fun merge(current: List<SavedCard>, backup: List<SavedCard>): Pair<List<SavedCard>, RestoreResult> {
        val byId = current.associateBy { it.id }
        var updated = 0
        val merged = current.map { card ->
            val old = backup.firstOrNull { it.id == card.id } ?: return@map card
            updated++
            val newer = if (old.lastScanned > card.lastScanned) old else card
            card.copy(
                balance = newer.balance,
                lastScanned = newer.lastScanned,
                addedAt = minOf(card.addedAt, old.addedAt),
                nickname = card.nickname ?: old.nickname,
                customImage = card.customImage ?: old.customImage,
                cardInfo = newer.cardInfo.ifEmpty { card.cardInfo.ifEmpty { old.cardInfo } },
                transactions = HistoryMerge.merge(old.transactions, card.transactions),
            )
        }
        val added = backup.filter { it.id !in byId }.distinctBy { it.id }
        return (merged + added) to RestoreResult(added = added.size, updated = updated)
    }

    /** Photo names are generated by the app; anything else in a backup is ignored. */
    fun isSafeImageName(name: String): Boolean = name.matches(Regex("[A-Za-z0-9_.-]{1,120}")) && !name.startsWith(".")
}
