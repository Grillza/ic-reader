    ("nimoca", "nimoca", "NI", "#F6C200", "#2B2B2B"),
    ("hayakaken", "Hayakaken", "H", "#D6001C", "#FFFFFF"),
    ("pitapa", "PiTaPa", "PT", "#14286E", "#FFFFFF"),
    ("transit", "Transit IC", "IC", "#455A64", "#FFFFFF"),
